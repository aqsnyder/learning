#!/usr/bin/env python3
"""Regenerate everything in this repo that is derived from data.

Sources (edit these):
  <curriculum>/<NN>-<slug>/resources.toml   the resources of one section
  <curriculum>/extras.toml                  books and courses with no section home (optional)
  the section READMEs                        all prose: objectives, suggested order, practice, questions

Generated (never edit by hand; run this script instead):
  - the Resources block of every section README, between <!-- resources:start … --> and <!-- resources:end -->
  - <curriculum>/PROGRESS.md: a blank checklist template with a stable ID on every line
  - the generated blocks in <curriculum>/books/README.md and <curriculum>/courses/README.md
  - the learning-path table in each curriculum README (you own the row order and the "When" column)
  - the section index in the root README

Usage:  python tools/build.py           # regenerate
        python tools/build.py --check   # exit 1 if anything is stale or invalid (CI runs this)
        python tools/build.py --only pcb            # regenerate one curriculum only
        python tools/build.py --only pcb/05,pcb/06  # regenerate only these sections' resource blocks
  --only exists so that several people (or agents) can edit different parts of the repo at once without one
  build overwriting another's work in progress. Run the plain command before committing.

Needs Python 3.11+ (for tomllib) and nothing else. The data format is documented in tools/README.md.
"""
import datetime
import os
import re
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SECTION_RE = re.compile(r"^(\d\d)-[a-z0-9-]+$")
ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")

CURRICULA = {
    # key: (canon meaning of ⭐, or None)
    "ml": "on Ilya Sutskever's reading list",
    "math": None,
    "physics": None,
    "bio": None,
    "econ": None,
    "philosophy": None,
    "pcb": "on Rick Hartley's reading list",
    "btc": "in the Bitcoin canon (see the curriculum README)",
    "software": None,
}

TYPES = {  # key: (emoji, default label)
    "book": ("📕", "Book"),
    "paper": ("📄", "Paper"),
    "article": ("📝", "Article"),
    "report": ("📊", "Report"),
    "blog": ("📰", "Blog"),
    "standard": ("📏", "Standard"),
    "app-note": ("📄", "App note"),
    "docs": ("📘", "Docs"),
    "tutorial": ("🧭", "Tutorial"),
    "course": ("🎓", "Course"),
    "lecture": ("🎤", "Lecture"),
    "video": ("🎥", "Video"),
    "video-series": ("📺", "Video series"),
    "encyclopedia": ("📚", "Encyclopedia"),
    "website": ("🌐", "Website"),
    "database": ("🗃️", "Database"),
    "tool": ("🔧", "Tool"),
    "podcast": ("🎙️", "Podcast"),
    "practice": ("🛠️", "Practice"),
    "concept": ("💡", "Concept"),
}
MARKS = {"masterwork": "🔑🔑", "core": "🔑", "canon": "⭐", "ai": "🤖"}
MARK_LEGEND = {"masterwork": "foundational masterwork", "core": "core path (read these first)", "ai": "AI-workflow item"}
ACCESS = {"free": "Free", "paid": "Paid", "partial": "Partly free"}
LEVELS = ["beginner", "intermediate", "advanced"]

ITEM_KEYS = {"id", "title", "type", "label", "authors", "year", "marks", "url", "link_text", "more_links",
             "link_note", "description", "access", "level", "verified", "track", "short"}
GROUP_KEYS = {"title", "intro", "outro", "items"}
TOP_KEYS = {"intro", "groups"}

RES_START = ("<!-- resources:start — generated by tools/build.py from resources.toml in this folder; "
             "edit that file, then run the script -->")
RES_END = "<!-- resources:end -->"
LP_START = ("<!-- learning-path:start — generated by tools/build.py: reorder rows or edit 'When' here; "
            "titles and core paths come from the section READMEs -->")
LP_END = "<!-- learning-path:end -->"
IX_START = ("<!-- section-index:start — generated by tools/build.py from the curriculum learning paths; "
            "do not edit by hand -->")
IX_END = "<!-- section-index:end -->"
IDX_START = "<!-- {kind}:start — generated by tools/build.py from the section data; do not edit by hand -->"
IDX_END = "<!-- {kind}:end -->"
ROW_RE = re.compile(r"^\|\s*\[Section (\d\d)\b[^\]]*\]\([^)]*\)\s*\|\s*(.*?)\s*\|")

errors = []


# ------------------------------------------------------------------ loading
def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


pending = []


def write_if_changed(path, text, check, stale):
    old = read(path) if os.path.exists(path) else None
    if old != text:
        stale.append(os.path.relpath(path, ROOT))
        pending.append((path, text))


def flush_writes():
    for path, text in pending:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def validate_item(it, where):
    for k in it:
        if k not in ITEM_KEYS:
            errors.append(f"{where}: unknown field '{k}'")
    for k in ("id", "title", "type"):
        if not it.get(k):
            errors.append(f"{where}: missing '{k}'")
    if it.get("id") and not ID_RE.match(it["id"]):
        errors.append(f"{where}: id '{it['id']}' must be lowercase letters, digits and hyphens")
    if it.get("type") and it["type"] not in TYPES:
        errors.append(f"{where}: unknown type '{it['type']}' (one of: {', '.join(TYPES)})")
    for m in it.get("marks", []):
        if m not in MARKS:
            errors.append(f"{where}: unknown mark '{m}' (one of: {', '.join(MARKS)})")
    if it.get("access") and it["access"] not in ACCESS:
        errors.append(f"{where}: access must be one of {', '.join(ACCESS)}")
    if it.get("level") and it["level"] not in LEVELS:
        errors.append(f"{where}: level must be one of {', '.join(LEVELS)}")
    if it.get("url") and not re.match(r"^(https?://|\.\./|\./)", it["url"]):
        errors.append(f"{where}: url must be absolute (https://…) or relative (../…)")
    for ml in it.get("more_links", []):
        if set(ml) - {"text", "url"} or not ml.get("url") or not ml.get("text"):
            errors.append(f"{where}: more_links entries need exactly 'text' and 'url'")
    v = it.get("verified")
    if v is not None and not isinstance(v, datetime.date):
        errors.append(f"{where}: verified must be a date like 2026-10-21 (no quotes)")


def load_toml(path):
    try:
        with open(path, "rb") as f:
            return tomllib.load(f)
    except tomllib.TOMLDecodeError as e:
        errors.append(f"{os.path.relpath(path, ROOT)}: {e}")
        return {}


def load_section_data(cur, sec):
    path = os.path.join(ROOT, cur, sec, "resources.toml")
    rel = os.path.relpath(path, ROOT)
    if not os.path.exists(path):
        errors.append(f"{rel}: missing")
        return {"groups": []}
    data = load_toml(path)
    for k in data:
        if k not in TOP_KEYS:
            errors.append(f"{rel}: unknown top-level field '{k}'")
    seen = set()
    for gi, g in enumerate(data.get("groups", []), 1):
        for k in g:
            if k not in GROUP_KEYS:
                errors.append(f"{rel}: group {gi}: unknown field '{k}'")
        for it in g.get("items", []):
            validate_item(it, f"{rel}: item '{it.get('id', '?')}'")
            if it.get("id") in seen:
                errors.append(f"{rel}: duplicate id '{it['id']}'")
            seen.add(it.get("id"))
    return data


def items_of(data):
    for g in data.get("groups", []):
        for it in g.get("items", []):
            yield it


# ------------------------------------------------------------------ section facts (from the README prose)
def section_facts(cur, sec):
    text = read(os.path.join(ROOT, cur, sec, "README.md"))
    h1 = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), sec)
    m = re.search(r"^\*\*Core path \(🔑\):\*\*\s*(.+)$", text, re.M)
    core = m.group(1).strip() if m else "(no Core path line)"
    practice = text.split("## 🛠️ Practice", 1)[1].split("## ✅ Check Yourself", 1)[0] if "## 🛠️ Practice" in text else ""
    exercises = []
    for mm in re.finditer(r"^(\d+)\.\s+\*\*(.+?)\*\*", practice, re.M):
        name = re.sub(r"[\s:—–-]+$", "", mm.group(2)).strip()
        exercises.append((int(mm.group(1)), name))
    mp = re.search(r"\*\*🏗️ Mini-project\s*[—–:-]\s*(.+?):?\*\*", text)
    mini = mp.group(1).strip().rstrip(":") if mp else None
    return {"dir": sec, "nn": sec[:2], "title": h1, "core": core, "exercises": exercises, "mini": mini, "text": text}


# ------------------------------------------------------------------ rendering helpers
def cell(s):
    s = (s or "").replace("\n", " ").strip()
    s = re.sub(r"(?<!\\)\|", r"\\|", s)
    return s or "—"


def type_cell(it):
    emoji, default = TYPES.get(it["type"], ("", it["type"]))
    label = it.get("label") or default
    acc = {"free": " (free)", "partial": " (partly free)"}.get(it.get("access"), "")
    return f"{emoji} {label}{acc}".strip()


def marks_cell(it):
    order = ["masterwork", "core", "canon", "ai"]
    return "".join(MARKS[m] for m in order if m in it.get("marks", []))


def link_cell(it):
    parts = []
    if it.get("url"):
        parts.append(f"[{it.get('link_text') or 'Link'}]({it['url']})")
    for ml in it.get("more_links", []):
        parts.append(f"[{ml['text']}]({ml['url']})")
    out = " · ".join(parts)
    if it.get("link_note"):
        out = (out + " " + it["link_note"]).strip()
    return out


def plain_title(t):
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", t)
    return t.strip()


def legend(cur, items):
    used = set(m for it in items for m in it.get("marks", []))
    parts = []
    for m in ["masterwork", "core", "canon", "ai"]:
        if m not in used:
            continue
        if m == "canon":
            meaning = CURRICULA.get(cur) or "on the curriculum's canon list"
        else:
            meaning = MARK_LEGEND[m]
        parts.append(f"{MARKS[m]} {meaning}")
    return ("*" + " · ".join(parts) + "*") if parts else ""


def render_table(items):
    out = ["| Priority | Type | Resource | Author(s) | Year | Link | Description |",
           "|---|---|---|---|---|---|---|"]
    for it in items:
        out.append("| " + " | ".join([
            marks_cell(it),
            cell(type_cell(it)),
            cell(it["title"]),
            cell(it.get("authors")),
            cell(str(it.get("year", "")) if it.get("year") else ""),
            cell(link_cell(it)),
            cell(it.get("description")),
        ]) + " |")
    return "\n".join(l.replace("|  |", "| |", 1) if l.startswith("|  |") else l for l in out)


def render_resources(cur, data):
    items = list(items_of(data))
    parts = [RES_START]
    lg = legend(cur, items)
    if lg:
        parts.append(lg)
    if data.get("intro"):
        parts.append(data["intro"].strip())
    for g in data.get("groups", []):
        if g.get("title"):
            parts.append(f"### {g['title']}")
        if g.get("intro"):
            parts.append(g["intro"].strip())
        if g.get("items"):
            parts.append(render_table(g["items"]))
        if g.get("outro"):
            parts.append(g["outro"].strip())
    parts.append(RES_END)
    return "\n\n".join(parts)


def replace_block(text, start_prefix, end, new_block, where):
    i = text.find(start_prefix)
    if i < 0:
        errors.append(f"{where}: no '{start_prefix}…' marker")
        return text
    k = text.find(end, i)
    if k < 0:
        errors.append(f"{where}: no '{end}' marker")
        return text
    return text[:i] + new_block + text[k + len(end):]


# ------------------------------------------------------------------ learning paths
def learning_path_order(cur, readme, secs):
    i = readme.find("<!-- learning-path:start")
    order = []
    if i >= 0:
        j = readme.find(LP_END, i)
        for line in readme[i:j].splitlines():
            m = ROW_RE.match(line)
            if m and m.group(1) in secs and m.group(1) not in [o for o, _ in order]:
                order.append((m.group(1), m.group(2).strip()))
    for nn in secs:
        if nn not in [o for o, _ in order]:
            order.append((nn, "(place me)"))
    return order


def render_learning_path(order, secs):
    rows = [LP_START, "| Section | When | Core path (🔑) |", "|---|---|---|"]
    for nn, when in order:
        s = secs[nn]
        rows.append(f"| [Section {nn} — {s['title']}]({s['dir']}/) | {when} | {s['core'].replace('|', chr(92) + '|')} |")
    rows.append(LP_END)
    return "\n".join(rows)


def curriculum_name(readme, cur):
    h1 = next((l[2:].strip() for l in readme.splitlines() if l.startswith("# ")), cur)
    return re.sub(r"\s+—\s+A Learning Journey\s*$", "", h1)


# ------------------------------------------------------------------ PROGRESS template
def progress_line(text, gid):
    return f"- [ ] {text} <!-- id:{gid} -->"


def render_progress(cur, name, order, secs, data_by_nn, extras):
    out = [f"# {name}: Progress Checklist", "",
           "> **This is a blank template. Don't tick boxes here.** Run `python tools/progress.py init` once:",
           "> it copies this checklist into `my/progress/`, which git ignores, so your ticks stay yours and",
           "> survive updates (`python tools/progress.py sync`). `python tools/progress.py status` draws your",
           "> progress bars. Generated by `tools/build.py` from the section data; don't edit by hand.", "",
           "A section counts as done when its 🔑 core items, at least two exercises and the first Check Yourself",
           "pass are ticked. Everything else is there for going deeper.", ""]
    for nn, when in order:
        s = secs[nn]
        out.append(f"## Section {nn} — {s['title']}")
        out.append("")
        for it in items_of(data_by_nn[nn]):
            if it.get("track") is False:
                continue
            label = plain_title(it["title"])
            if it.get("short"):
                label = it["short"]
            elif it.get("authors"):
                label = f"{label} — {it['authors']}"
            key = "🔑 " if ("core" in it.get("marks", []) or "masterwork" in it.get("marks", [])) else ""
            out.append(progress_line(f"{key}{label}", f"{cur}/{nn}/{it['id']}"))
        for n, ename in s["exercises"]:
            out.append(progress_line(f"🛠️ Exercise {n}: {ename}", f"{cur}/{nn}/ex-{n}"))
        if s["mini"]:
            out.append(progress_line(f"🏗️ Mini-project: {s['mini']}", f"{cur}/{nn}/mini-project"))
        out.append(progress_line("✅ Check Yourself, answered from memory", f"{cur}/{nn}/check-1"))
        out.append(progress_line("✅ Check Yourself again, a week later", f"{cur}/{nn}/check-2"))
        out.append(progress_line("✅ Check Yourself again, a month later", f"{cur}/{nn}/check-3"))
        out.append(progress_line("📝 One-page note written in `my/notes/`", f"{cur}/{nn}/note"))
        out.append("")
    ex_items = [it for it in items_of(extras) if it.get("track") is not False]
    if ex_items:
        out.append("## Further reading (no section home)")
        out.append("")
        for it in ex_items:
            label = plain_title(it["title"]) + (f" — {it['authors']}" if it.get("authors") else "")
            out.append(progress_line(label, f"{cur}/extras/{it['id']}"))
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# ------------------------------------------------------------------ books / courses indexes
def dedup_keys(it):
    """Keys under which two items count as the same resource: the URL, and title + first author."""
    keys = []
    u = (it.get("url") or "").lower().rstrip("/")
    u = re.sub(r"^https?://(www\.)?", "", u)
    if u and not u.startswith(".."):
        keys.append("u:" + u)
    t = re.sub(r"\(.*?\)|[*_]", " ", plain_title(it["title"]).lower()).split(":")[0]
    t = re.sub(r"^(the|a|an)\s+", "", t.strip())
    t = re.sub(r"[^a-z0-9]+", " ", t).strip()
    a = re.split(r",|&| and |;", (it.get("authors") or "").lower())[0].strip()
    a = re.sub(r"[^a-z ]+", "", a).split()
    keys.append("t:" + t + "|" + (a[-1] if a else ""))
    return keys


INDEX_KINDS = {"books": {"book"}, "courses": {"course", "video-series", "lecture", "video"}}


def render_index(kind, cur, order, secs, data_by_nn, extras):
    kinds = INDEX_KINDS[kind]
    entries = []      # each: {"it", "secs", "marks"}
    key_to_entry = {}

    def add(it, nn):
        keys = dedup_keys(it)
        e = next((key_to_entry[k] for k in keys if k in key_to_entry), None)
        if e is None:
            e = {"it": dict(it), "secs": [], "marks": set()}
            entries.append(e)
        for k in keys:
            key_to_entry.setdefault(k, e)
        if nn:
            e["secs"].append(nn)
        e["marks"] |= set(it.get("marks", []))
        for f in ("level", "access", "year", "authors", "url", "link_text"):
            if not e["it"].get(f) and it.get(f):
                e["it"][f] = it[f]

    for nn, _ in order:
        for it in items_of(data_by_nn[nn]):
            if it["type"] in kinds:
                add(it, nn)
    for it in items_of(extras):
        if it["type"] in kinds:
            add(it, None)
    lvl = {l: i for i, l in enumerate(LEVELS)}
    entries.sort(key=lambda e: lvl.get(e["it"].get("level"), len(LEVELS)))
    head = {"books": "| # | Priority | Title | Author(s) | Year | Access | Level | Link | Used in |",
            "courses": "| # | Priority | Course or lecture | Instructor / Source | Year | Access | Level | Link | Used in |"}[kind]
    rows = [IDX_START.format(kind=kind), head, "|---|---|---|---|---|---|---|---|---|"]
    pos = {o: i for i, (o, _) in enumerate(order)}
    for n, e in enumerate(entries, 1):
        it = e["it"]
        used = ", ".join(f"[{nn}](../{secs[nn]['dir']}/README.md)" for nn in sorted(set(e["secs"]), key=lambda x: pos[x]))
        cells = [str(n), marks_cell({"marks": sorted(e["marks"])}),
                 cell(it["title"]), cell(it.get("authors")),
                 cell(str(it.get("year", "")) if it.get("year") else ""),
                 cell(ACCESS.get(it.get("access"), "")), cell((it.get("level") or "").capitalize()),
                 cell(link_cell(it)), used or "Further reading"]
        rows.append(("| " + " | ".join(cells) + " |").replace(" |  | ", " | | ", 1))
    rows.append(IDX_END.format(kind=kind))
    return "\n".join(rows)


# ------------------------------------------------------------------ main
def parse_only():
    if "--only" not in sys.argv:
        return None
    i = sys.argv.index("--only")
    if i + 1 >= len(sys.argv):
        sys.exit("--only needs a value, e.g. --only pcb or --only pcb/05,pcb/06")
    return [x.strip().strip("/") for x in sys.argv[i + 1].split(",") if x.strip()]


def main():
    check = "--check" in sys.argv
    only = parse_only()
    whole = None if only is None else {o for o in only if "/" not in o}
    secs_only = None if only is None else {o for o in only if "/" in o}
    stale = []
    index_parts = []
    for cur in CURRICULA:
        if only is not None and cur not in whole and not any(s.startswith(cur + "/") for s in secs_only):
            continue
        cur_level = only is None or cur in whole
        cdir = os.path.join(ROOT, cur)
        sec_dirs = sorted(d for d in os.listdir(cdir) if SECTION_RE.match(d))
        secs = {d[:2]: section_facts(cur, d) for d in sec_dirs}
        data_by_nn = {d[:2]: load_section_data(cur, d) for d in sec_dirs}
        extras_path = os.path.join(cdir, "extras.toml")
        extras = load_toml(extras_path) if os.path.exists(extras_path) else {"groups": []}
        for gi, g in enumerate(extras.get("groups", []), 1):
            for it in g.get("items", []):
                validate_item(it, f"{cur}/extras.toml: item '{it.get('id', '?')}'")
        # section READMEs
        for d in sec_dirs:
            if not cur_level and f"{cur}/{d[:2]}" not in secs_only:
                continue
            p = os.path.join(cdir, d, "README.md")
            text = secs[d[:2]]["text"]
            new = replace_block(text, "<!-- resources:start", RES_END, render_resources(cur, data_by_nn[d[:2]]),
                                os.path.relpath(p, ROOT))
            write_if_changed(p, new, check, stale)
        if not cur_level:
            continue
        # learning path
        rp = os.path.join(cdir, "README.md")
        readme = read(rp)
        order = learning_path_order(cur, readme, secs)
        new = replace_block(readme, "<!-- learning-path:start", LP_END, render_learning_path(order, secs),
                            os.path.relpath(rp, ROOT))
        write_if_changed(rp, new, check, stale)
        name = curriculum_name(readme, cur)
        # PROGRESS template
        write_if_changed(os.path.join(cdir, "PROGRESS.md"),
                         render_progress(cur, name, order, secs, data_by_nn, extras), check, stale)
        # indexes
        for kind in ("books", "courses"):
            ip = os.path.join(cdir, kind, "README.md")
            if os.path.exists(ip):
                t = read(ip)
                new = replace_block(t, f"<!-- {kind}:start", IDX_END.format(kind=kind),
                                    render_index(kind, cur, order, secs, data_by_nn, extras), os.path.relpath(ip, ROOT))
                write_if_changed(ip, new, check, stale)
        # root index part
        items = []
        for nn, when in order:
            s = secs[nn]
            note = f" · {when}" if when and when != "(place me)" else ""
            items.append(f"- [{nn} — {s['title']}]({cur}/{s['dir']}/){note}")
        index_parts.append(f"<details>\n<summary><b>{name}</b> · {len(order)} sections · "
                           f"<a href=\"{cur}/\">curriculum page</a></summary>\n\n" + "\n".join(items) + "\n\n</details>\n")
    if only is not None:
        return finish(check, stale)
    root_path = os.path.join(ROOT, "README.md")
    root = read(root_path)
    new = replace_block(root, "<!-- section-index:start", IX_END, IX_START + "\n" + "\n".join(index_parts) + IX_END,
                        "README.md")
    write_if_changed(root_path, new, check, stale)
    finish(check, stale)


def finish(check, stale):
    if errors:
        for e in errors:
            print("  " + e, file=sys.stderr)
        print(f"{len(errors)} data error(s)", file=sys.stderr)
        sys.exit(1)
    if check:
        for s in stale:
            print(f"  {s}: out of date (run: python tools/build.py)", file=sys.stderr)
        sys.exit(1 if stale else 0)
    flush_writes()
    print(f"updated {len(stale)} file(s)" if stale else "everything already up to date")


if __name__ == "__main__":
    main()
