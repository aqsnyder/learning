#!/usr/bin/env python3
"""Regenerate the learning-path tables and the root section index from the section READMEs.

Each curriculum README has a block

    <!-- learning-path:start ... -->
    | Section | When | Core path (🔑) |
    |---|---|---|
    | [Section 00 — Historical Foundations of AI](00-historical-foundations/) | Start here | Turing 1950 → … |
    <!-- learning-path:end -->

You own the row ORDER and the "When" column: edit them in the README and this tool keeps them.
The tool owns the link, the title (each section README's H1) and the core path (its
"**Core path (🔑):**" line), so those never go stale. A section missing from the table is
appended at the end with "When" set to "(place me)"; move that row to where it belongs.

The root README has a block <!-- section-index:start --> … <!-- section-index:end --> listing
every section of every curriculum in learning-path order. It is fully generated.

Usage:  python tools/build_index.py          # rewrite the blocks in place
        python tools/build_index.py --check  # exit 1 if any block is out of date (check_repo.py runs this)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CURRICULA = ["ml", "math", "physics", "bio", "econ", "philosophy", "pcb", "btc", "software"]
SECTION_RE = re.compile(r"^(\d\d)-[a-z0-9-]+$")
LP_START = "<!-- learning-path:start — generated by tools/build_index.py: reorder rows or edit 'When' here; titles and core paths come from the section READMEs -->"
LP_END = "<!-- learning-path:end -->"
IX_START = "<!-- section-index:start — generated by tools/build_index.py from the curriculum learning paths; do not edit by hand -->"
IX_END = "<!-- section-index:end -->"
ROW_RE = re.compile(r"^\|\s*\[Section (\d\d)\b[^\]]*\]\([^)]*\)\s*\|\s*(.*?)\s*\|")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def block(text, start_prefix, end):
    """Return (before, inner, after) around a marker block, or None if absent."""
    i = text.find(start_prefix)
    if i < 0:
        return None
    j = text.find("\n", i)
    k = text.find(end, j)
    if j < 0 or k < 0:
        return None
    return text[: j + 1], text[j + 1 : k], text[k:]


def sections(cur):
    out = {}
    cdir = os.path.join(ROOT, cur)
    for d in sorted(os.listdir(cdir)):
        if not SECTION_RE.match(d):
            continue
        text = read(os.path.join(cdir, d, "README.md"))
        h1 = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), d)
        m = re.search(r"^\*\*Core path \(🔑\):\*\*\s*(.+)$", text, re.M)
        core = m.group(1).strip() if m else "(no Core path line)"
        out[d[:2]] = {"dir": d, "title": h1, "core": core.replace("|", "\\|")}
    return out


def learning_path(cur, readme):
    """Return the regenerated table (inner block text) and the ordered (nn, when) list."""
    secs = sections(cur)
    b = block(readme, "<!-- learning-path:start", LP_END)
    order = []
    if b:
        for line in b[1].splitlines():
            m = ROW_RE.match(line)
            if m and m.group(1) in secs and m.group(1) not in [o for o, _ in order]:
                order.append((m.group(1), m.group(2).strip()))
    for nn in secs:
        if nn not in [o for o, _ in order]:
            order.append((nn, "(place me)"))
    rows = ["| Section | When | Core path (🔑) |", "|---|---|---|"]
    for nn, when in order:
        s = secs[nn]
        rows.append(f"| [Section {nn} — {s['title']}]({s['dir']}/) | {when} | {s['core']} |")
    return "\n".join(rows) + "\n", order, secs


def curriculum_name(readme, cur):
    h1 = next((l[2:].strip() for l in readme.splitlines() if l.startswith("# ")), cur)
    return re.sub(r"\s+—\s+A Learning Journey\s*$", "", h1)


def main():
    check = "--check" in sys.argv
    stale = []
    index_parts = []
    for cur in CURRICULA:
        path = os.path.join(ROOT, cur, "README.md")
        readme = read(path)
        b = block(readme, "<!-- learning-path:start", LP_END)
        if not b:
            stale.append(f"{cur}/README.md: no learning-path block")
            continue
        table, order, secs = learning_path(cur, readme)
        before, inner, after = b
        # normalise the start marker line itself
        start_line_begin = before.rfind("<!-- learning-path:start")
        before = before[:start_line_begin] + LP_START + "\n"
        new = before + table + after
        if new != readme:
            stale.append(f"{cur}/README.md: learning-path table is out of date")
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(new)
        name = curriculum_name(readme, cur)
        items = []
        for nn, when in order:
            s = secs[nn]
            note = f" · {when}" if when and when != "(place me)" else ""
            items.append(f"- [{nn} — {s['title']}]({cur}/{s['dir']}/){note}")
        index_parts.append(
            f"<details>\n<summary><b>{name}</b> · {len(order)} sections · "
            f"<a href=\"{cur}/\">curriculum page</a></summary>\n\n" + "\n".join(items) + "\n\n</details>\n"
        )
    root_path = os.path.join(ROOT, "README.md")
    root = read(root_path)
    b = block(root, "<!-- section-index:start", IX_END)
    if not b:
        stale.append("README.md: no section-index block")
    else:
        before, inner, after = b
        start_line_begin = before.rfind("<!-- section-index:start")
        before = before[:start_line_begin] + IX_START + "\n"
        new = before + "\n".join(index_parts) + after
        if new != root:
            stale.append("README.md: section index is out of date")
            if not check:
                with open(root_path, "w", encoding="utf-8") as f:
                    f.write(new)
    if check:
        for s in stale:
            print("  " + s + " (run: python tools/build_index.py)", file=sys.stderr)
        sys.exit(1 if stale else 0)
    print(f"updated {len(stale)} block(s)" if stale else "all blocks already up to date")


if __name__ == "__main__":
    main()
